"""Nightly job: rewrite the region cache from the registry.

Runs on the platform network with GRID9_REGISTRY_TOKEN in the environment;
see docs/region-registry.md and the sync job in .github/workflows/ci.yml.
"""

import pathlib
import sys

from .registry import RegistryClient, RegistryUnavailable

CACHE = pathlib.Path(__file__).resolve().parent / "region_cache.py"
HEADER = '"""Generated by the nightly region sync job. Do not edit by hand.\n\nEvery entry here was served by the Grid9 region registry on the last\nsuccessful sync; see docs/region-registry.md.\n"""\n'


def render(catalogue: dict[str, str]) -> str:
    body = "".join(f'    "{code}": "{name}",\n' for code, name in sorted(catalogue.items()))
    return HEADER + "\nREGION_NAMES = {\n" + body + "}\n"


def main(argv: list[str]) -> int:
    try:
        catalogue = RegistryClient().fetch_regions()
    except RegistryUnavailable as err:
        print(f"region sync skipped: {err}", file=sys.stderr)
        return 2
    CACHE.write_text(render(catalogue))
    print(f"region sync wrote {len(catalogue)} regions")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
